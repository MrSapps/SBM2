"""Writes a C header with anti-aliased glyph bitmaps (ASCII 32..126) of a
monospace TrueType font, for build/port/play's overlays (port/overlay.c).
Generated into build/ at build time; needs Pillow and the font.

Usage: mkfont.py OUT.h [FONT.ttf [BOLD.ttf]]
"""
import sys
from PIL import Image, ImageDraw, ImageFont

out = sys.argv[1]
reg = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf'
bold = sys.argv[3] if len(sys.argv) > 3 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf'
# (name, file, pixel size)
FACES = [('small', reg, 17), ('mid', reg, 22), ('big', bold, 30), ('huge', bold, 44)]

lines = ['/* Generated by port/mkfont.py: glyph alpha, ASCII 32..126. */',
         'typedef struct { int w, h; const unsigned char *a; } OvFont;']
for name, path, size in FACES:
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    w, h = int(round(f.getlength('M'))), asc + desc
    data = []
    for c in range(32, 127):
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
        data.extend(im.tobytes())
    lines.append(f'static const unsigned char ov_{name}_a[{len(data)}] = {{')
    for i in range(0, len(data), 32):
        lines.append(','.join(str(b) for b in data[i:i + 32]) + ',')
    lines.append('};')
    lines.append(f'static const OvFont ov_{name} = {{{w}, {h}, ov_{name}_a}};')
open(out, 'w').write('\n'.join(lines) + '\n')
