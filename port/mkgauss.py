"""Writes build/port/gauss.h: the S-DSP's 512-entry interpolation table.

The table is the chip's own data, so it is not in git. It is read from
Mesen 2's source (tools/mesen2-src, see README) when that is there; without
it a fitted Gaussian stands in (close, not exact).

Usage: mkgauss.py OUT.h [DspInterpolation.h]
"""
import math
import os
import re
import sys

out = sys.argv[1]
src = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(__file__), '..', 'tools', 'mesen2-src', 'Core', 'SNES', 'DSP', 'DspInterpolation.h')
vals, how = None, 'fitted'
if os.path.exists(src):
    m = re.search(r'gauss\s*\[\s*512\s*\]\s*=\s*\{([^}]*)\}', open(src).read())
    if m:
        v = [int(x) for x in m.group(1).replace('\n', ' ').split(',') if x.strip()]
        if len(v) == 512:
            vals, how = v, 'from ' + os.path.relpath(src)
if vals is None:
    # 0 at the far tap, 1305 at the centre (i = 511), ~370 one sample out
    vals = [round(1305 * math.exp(-1.26 * ((511 - i) / 256) ** 2)) if i >= 16 else 0 for i in range(512)]
with open(out, 'w') as f:
    f.write(f'/* Generated by port/mkgauss.py ({how}). */\n')
    f.write('static const int16_t gauss[512] = {\n')
    for i in range(0, 512, 16):
        f.write(' ' + ','.join(f'{x:5d}' for x in vals[i:i + 16]) + ',\n')
    f.write('};\n')
